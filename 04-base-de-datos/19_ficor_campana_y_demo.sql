-- ============================================================================
-- 19 · Ficorremediación: campaña por medición y datos de demostración en la base
--
-- El tablero del ICA calculaba sobre constantes del navegador, así que no leía
-- la geodatabase y no habría leído las mediciones reales aunque existieran. Las
-- tablas no podían sostenerlo: no guardaban a qué campaña ni a qué punto
-- pertenece cada medición.
--
-- Esta migración añade `campana` y `es_demostracion`, y siembra en la base los
-- valores que estaban en el código, marcados como demostración. Desde aquí la
-- pantalla lee la geodatabase siempre; el aviso de «datos de demostración»
-- aparece solo si lo que devuelve la base viene marcado.
--
-- Cuando el laboratorio entregue el muestreo 1:
--     DELETE FROM eco_restauracion.ficor_calidad_agua       WHERE es_demostracion;
--     DELETE FROM eco_restauracion.ficor_calidad_sedimentos WHERE es_demostracion;
--     DELETE FROM eco_restauracion.ficor_biota              WHERE es_demostracion;
-- y se cargan los resultados por el formulario o por importación.
--
-- Idempotente: re-ejecutarla no duplica las filas de demostración.
-- ============================================================================
SET search_path TO eco_restauracion, public;

ALTER TABLE eco_restauracion.ficor_calidad_agua
    ADD COLUMN IF NOT EXISTS campana TEXT,
    ADD COLUMN IF NOT EXISTS es_demostracion BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE eco_restauracion.ficor_calidad_sedimentos
    ADD COLUMN IF NOT EXISTS campana TEXT,
    ADD COLUMN IF NOT EXISTS es_demostracion BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE eco_restauracion.ficor_biota
    ADD COLUMN IF NOT EXISTS campana TEXT,
    ADD COLUMN IF NOT EXISTS es_demostracion BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN eco_restauracion.ficor_calidad_agua.es_demostracion IS
    'TRUE: valor de demostración, no resultado de laboratorio. La pantalla lo advierte.';

CREATE INDEX IF NOT EXISTS idx_ficor_agua_campana ON eco_restauracion.ficor_calidad_agua (campana);
CREATE INDEX IF NOT EXISTS idx_ficor_sed_campana  ON eco_restauracion.ficor_calidad_sedimentos (campana);
CREATE INDEX IF NOT EXISTS idx_ficor_biota_campana ON eco_restauracion.ficor_biota (campana);

-- Borra solo la siembra anterior de demostración, nunca mediciones reales.
DELETE FROM eco_restauracion.ficor_calidad_agua       WHERE es_demostracion;
DELETE FROM eco_restauracion.ficor_calidad_sedimentos WHERE es_demostracion;
DELETE FROM eco_restauracion.ficor_biota              WHERE es_demostracion;

